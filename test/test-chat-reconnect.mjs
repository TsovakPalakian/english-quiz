test('a group receipt splits one reader from everyone',()=>{
  const messages=readFileSync(new URL('../production/chat/40-messages.js',import.meta.url),'utf8');
  const marks=runInNewContext(extractFunction(messages,'chatReceiptMarks')+'\nchatReceiptMarks');
  const face=runInNewContext(extractFunction(messages,'chatReceiptFace')+'\nchatReceiptFace');
  const readers=[{id:'alice',read:0,delivered:1},{id:'bob',read:0,delivered:1},{id:'teacher',read:0,delivered:0}];
  const delivered=marks(1,readers,'alice',true);
  assert.equal(delivered.delivered,true);
  assert.equal(delivered.read,false);
  assert.equal(delivered.readSome,false);
  assert.equal(delivered.memberCount,2);
  readers[1].read=1;
  const one=marks(1,readers,'alice',true);
  assert.equal(one.read,false);
  assert.equal(one.readSome,true);
  assert.equal(one.readCount,1);
  assert.equal(face(one).label,'Read by 1 of 2');
  assert.equal(face(one).read,false);
  assert.equal(face(one).some,true);
  readers[2].read=1;readers[2].delivered=1;
  const all=marks(1,readers,'alice',true);
  assert.equal(all.read,true);
  assert.equal(face(all).title,'Read by everyone');
  const direct=marks(1,[{id:'bob',read:0,delivered:0}],'alice',false);
  assert.equal(direct.delivered,false);
  assert.equal(direct.read,false);
  assert.equal(marks(1,[{id:'bob',read:1,delivered:1}],'alice',false).read,true);
});
test('an unconfirmed send keeps its client key when the text changes',()=>{
  const messages=readFileSync(new URL('../production/chat/40-messages.js',import.meta.url),'utf8');
  const settings=readFileSync(new URL('../production/chat/90-settings.js',import.meta.url),'utf8');
  const draft=runInNewContext(extractFunction(messages,'chatSendDraft')+'\nchatSendDraft',{crypto});
  const key=runInNewContext(extractFunction(settings,'chatCalendarReportKey')+'\nchatCalendarReportKey',{crypto});
  const done=runInNewContext(extractFunction(settings,'chatCalendarReportDone')+'\nchatCalendarReportDone');
  const saved={roomId:'direct:a:b',text:'once',category:'personal',clientKey:'keep',createdMs:10};
  assert.equal(draft(saved,{...saved,text:'twice'}).clientKey,'keep');
  assert.equal(draft(saved,{...saved,text:'twice'}).createdMs,10);
  assert.equal(draft(null,{roomId:'direct:a:b',text:'after'}).clientKey!=='keep',true);
  const store=new Map();
  const first=key(store,1,'learning','report');
  assert.equal(key(store,1,'learning','report'),first);
  assert.notEqual(key(store,1,'learning','other'),first);
  done(store,1,'learning','report');
  assert.notEqual(key(store,1,'learning','report'),first);
  assert.match(extractFunction(messages,'send'),/chatSendDraft\(pending, body\)/);
  assert.match(settings,/chatCalendarReportKey\(calendarReportKeys/);
  assert.doesNotMatch(settings,/gcw-report-' \+ Date\.now\(\)/);
});
