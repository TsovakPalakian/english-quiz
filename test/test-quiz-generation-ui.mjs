import {chromiumExecutable,resolveTestDependency} from '../ops/check-environment.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createQuizReviewPreview} from '../ops/preview-quiz-review-backend.mjs';
import {QUIZ_TYPES} from '../src/learning-study.mjs';
import {scenarioSubtests} from "./helpers/scenario-subtests.mjs";
const require=createRequire(import.meta.url);
const {chromium}=require(resolveTestDependency('playwright'));
test('local preparation shows retries, teacher issues and automatic provenance without publishing templates',async()=>scenarioSubtests("local preparation shows retries, teacher issues and automatic provenance without publishing templates phases",async function*(){
yield "00. Fixture and browser setup";

  const {server,url}=await createQuizReviewPreview({generationEnabled:true});let browser;
  try{
    browser=await chromium.launch({headless:true,executablePath:chromiumExecutable()});
    const page=await browser.newPage({viewport:{width:1280,height:960}}),errors=[],requests=[];
    page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(r.url()));
    // Seed all job outcomes through the authenticated API; kit selection has its own UI tests.
    const prepare=()=>page.evaluate(async types=>{
      const {contexts}=await(await fetch('/local/boot')).json(),c=contexts[0];
      const response=await fetch('/local/generation',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({mutationId:crypto.randomUUID(),groupId:c.groupId,lessonId:c.lessonId,cardId:c.cardId,senseId:c.senseId,types})});
      if(!response.ok)throw new Error(await response.text());
    },QUIZ_TYPES);
    await page.goto(url);await page.locator('#context').waitFor();
    yield "01. checks";
    await prepare();
    await page.locator('[data-view="word"]').click();
    await page.waitForFunction(async()=>{const response=await fetch('/local/generation'),{jobs}=await response.json();return jobs.length===16&&jobs.every(j=>!['queued','running','retry'].includes(j.state));},{},{timeout:20000});
    await page.waitForFunction(()=>document.querySelectorAll('[data-job]').length===16&&![...document.querySelectorAll('[data-job]')].some(n=>['queued','running','retry'].includes(n.dataset.jobState)));
    yield "02. evaluate";
    const {jobs}=await page.evaluate(async()=>await(await fetch('/local/generation')).json());
    assert.equal(jobs.find(j=>j.type==='Choice').attempts,3);assert.equal(jobs.find(j=>j.type==='Choice').state,'review');
    assert.equal(jobs.find(j=>j.type==='Gap').attempts,2);assert.equal(jobs.find(j=>j.type==='Gap').state,'submitted');
    assert.equal(jobs.find(j=>j.type==='Listen').attempts,1);assert.equal(jobs.find(j=>j.type==='Match').attempts,0);
    const attemptPath='/local/generation/'+jobs.find(j=>j.type==='Choice').id+'/attempts';
    const attemptLog=await page.evaluate(async path=>(await(await fetch(path)).json()).attempts,attemptPath);
    assert.equal(attemptLog.length,3);assert.ok(attemptLog.every(a=>a.state==='rejected'&&Object.keys(a.usage).length===0&&a.source.model==='local-fixture-a'));
    assert.equal((await fetch(url+attemptPath,{headers:{Cookie:'qr-preview=student'}})).status,403);
    const shared=await page.evaluate(async()=>await(await fetch('/local/shared/1')).json());assert.equal(shared.quizzes.length,1,'Only the pre-approved seed is shared');
    yield "03. checks";
    await prepare();
    assert.equal((await page.evaluate(async()=>await(await fetch('/local/generation')).json())).jobs.length,16,'Enqueue is deduplicated');
    const gap=jobs.find(j=>j.type==='Gap');await page.locator('[data-job="'+gap.id+'"] > summary').click();
    await page.locator('[data-job="'+gap.id+'"] [data-action="open-generated"]').click();
    yield "04. [data-item=\"'+gap.versionId+'\"] / checks";
    await page.locator('[data-item="'+gap.versionId+'"]').waitFor({state:'visible'});
    assert.match(await page.locator('[data-item="'+gap.versionId+'"]').innerText(),/Automatic generator/);
    assert.equal(await page.locator('[data-item="'+gap.versionId+'"] .verified').count(),0);
    assert.equal(await page.locator('.generation-job[data-job-state="review"]').count(),2);
    const choice=jobs.find(j=>j.type==='Choice');
    yield "05. [data-job=\"'+choice.id+'\"] > summary / click";
    await page.locator('[data-job="'+choice.id+'"] > summary').click();
    await Promise.resolve();
    await page.setViewportSize({width:390,height:844});await page.locator('[data-job="'+choice.id+'"]').scrollIntoViewIfNeeded();
    yield "06. evaluate";
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await Promise.resolve();
    await page.locator('[data-job="'+choice.id+'"] [data-action="retry-job"]').click();
    await page.waitForFunction(async id=>(await(await fetch('/local/generation')).json()).jobs.find(j=>j.id===id).cycle===1,choice.id);
    yield "07. evaluate";
    const boot=await page.evaluate(async()=>await(await fetch('/local/boot')).json()),c=boot.contexts[0];
    const denied=await fetch(url+'/local/generation',{method:'POST',headers:{Origin:url,'Content-Type':'application/json',Cookie:'qr-preview=student'},body:JSON.stringify({mutationId:crypto.randomUUID(),groupId:c.groupId,lessonId:c.lessonId,cardId:c.cardId,senseId:c.senseId,types:['Gap']})});assert.equal(denied.status,403);
    await page.evaluate(async id=>{
      const {quiz}=await(await fetch('/local/quizzes/'+id)).json();
      const response=await fetch('/local/quizzes/'+id+'/approve',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({mutationId:crypto.randomUUID(),expectedRevision:quiz.revision,checks:{meaning:true,answers:true,level:true}})});if(!response.ok)throw new Error('Approval failed');
    },gap.versionId);
    await page.locator('[data-view="word"]').click();
    yield "08. [data-job=\"'+gap.id+'\"] / checks";
    await page.locator('[data-job="'+gap.id+'"]').waitFor({state:'attached'});
    await page.locator('[data-job="'+gap.id+'"]').evaluate(n=>n.open=true);
    await page.locator('[data-job="'+gap.id+'"] [data-action="open-generated"]').click();
    await page.locator('[data-item="'+gap.versionId+'"] .verified').waitFor({state:'visible'});
    yield "09. waitForFunction";
    await page.waitForFunction(async id=>{const {jobs}=await(await fetch('/local/generation')).json();return jobs.find(j=>j.id===id)?.state==='review';},choice.id);
    await page.locator('[data-job="'+choice.id+'"]').evaluate(n=>n.open=true);
    await page.locator('[data-job="'+choice.id+'"] [data-action="repair-job"]').click();
    assert.equal(await page.locator('#edit-type').inputValue(),'Choice');
    yield "10. #edit-type / checks";
    assert.equal(await page.locator('#edit-type').isDisabled(),true);
    await page.locator('[data-editor-item="0"] [data-option="0"]').fill('изморось');
    await page.locator('[data-editor-item="0"] [data-option="1"]').fill('гроза');
    await page.getByRole('button',{name:'Save draft',exact:true}).click();
    yield "11. #editor / checks";
    await page.locator('#editor').waitFor({state:'hidden'});
    const replaced=await page.evaluate(async id=>(await(await fetch('/local/generation')).json()).jobs.find(j=>j.id===id),choice.id);
    assert.equal(replaced.quizState,'draft');assert.equal(replaced.issue,'invalid_content');
    const replacementId=replaced.versionId;
    await page.locator('[data-item="'+replacementId+'"]').evaluate(node=>{for(let n=node;n;n=n.parentElement)if(n.tagName==='DETAILS')n.open=true;});
    await page.locator('[data-item="'+replacementId+'"] [data-action="submit"]').click();
    yield "12. waitForFunction";
    await page.waitForFunction(id=>!document.querySelector('[data-item="'+id+'"] [data-action="edit"]'),replacementId);
    assert.equal(await page.locator('[data-item="'+replacementId+'"] [data-action="approve"]').count(),0,'No self approval');
    await page.locator('#account').selectOption('second');await page.waitForFunction(()=>document.querySelector('#account').value==='second'&&!document.querySelector('#account').disabled);
    yield "13. [data-view=\"queue\"] / click";
    await page.locator('[data-view="queue"]').click();await page.locator('[data-item="'+replacementId+'"]').evaluate(node=>{for(let n=node;n;n=n.parentElement)if(n.tagName==='DETAILS')n.open=true;});
    assert.equal(await page.locator('[data-job="'+choice.id+'"]').count(),1,'Issue stays active until approval');
    await page.locator('[data-item="'+replacementId+'"] [data-action="approve"]').click();for(const box of await page.locator('#decision input[type="checkbox"]').all())await box.check();
    yield "14. #decision-confirm / click";
    await page.locator('#decision-confirm').click();await page.locator('#decision').waitFor({state:'hidden'});
    await page.waitForFunction(id=>!document.querySelector('[data-job="'+id+'"]'),choice.id);
    await page.locator('[data-view="word"]').click();
    yield "15. [data-item=\"'+replacementId+'\"] / evaluate";
    await page.locator('[data-item="'+replacementId+'"]').evaluate(node=>{for(let n=node;n;n=n.parentElement)if(n.tagName==='DETAILS')n.open=true;});
    await page.locator('[data-item="'+replacementId+'"] .verified').scrollIntoViewIfNeeded();
    await Promise.resolve();
    assert.deepEqual(errors,[]);assert.ok(requests.every(u=>u.startsWith(url)));
  }finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}

}));
