import {chromiumExecutable,resolveTestDependency} from '../ops/check-environment.mjs';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(resolveTestDependency('playwright'));
const server=spawn(process.execPath,['ops/preview-dashboard.mjs'],{env:{...process.env,PORT:'0',PREVIEW_ROLE:'DEVELOPER'},stdio:['ignore','pipe','pipe']});
let browser;
try{
  const url=await new Promise((resolve,reject)=>{server.on('error',reject);server.stdout.on('data',chunk=>{const match=String(chunk).match(/http:\/\/127\.0\.0\.1:\d+/);if(match)resolve(match[0]);});server.on('exit',code=>reject(Error('Preview exited '+code)));});
  browser=await chromium.launch({headless:true,executablePath:chromiumExecutable()});
  const page=await browser.newPage({viewport:{width:1280,height:1000},timezoneId:'Asia/Yerevan'}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>sessionStorage.setItem('enquiz-place',JSON.stringify({id:'bugs'})));
  await page.goto(url);await page.locator('[data-bug-day]').first().waitFor({timeout:30000});
  assert.deepEqual(await page.locator('[data-bug-day]').evaluateAll(nodes=>nodes.map(node=>node.dataset.bugDay)),['2026-10-20','2026-10-19']);
  await Promise.resolve();
  await page.locator('#bugListSearch').fill('Connection interrupted');
  await page.waitForFunction(()=>document.querySelector('[data-bug-day="2026-10-19"]').open);
  assert.equal(await page.locator('[data-bug-day="2026-10-20"]').isVisible(),false);
  await page.locator('#bugListSearch').fill('');
  await page.locator('[data-bug-day="2026-10-20"]').waitFor({state:'visible'});
  const first=page.locator('[data-bug="'+ '1'.repeat(32)+'"]');
  await first.click();
  assert.equal(await first.getAttribute('aria-expanded'),'true',JSON.stringify(errors));
  const history=page.locator('[data-bug-history="'+'1'.repeat(32)+'"]');assert.equal(await history.getAttribute('open'),null);
  await history.locator('summary').click();
  assert.match((await history.innerText()),/20 October 2026 — 2 occurrences/);assert.match(await history.innerText(),/Resolved:/);
  await Promise.resolve();
  await page.locator('[data-bug-tab="done"]').click();
  assert.deepEqual(await page.locator('[data-bug-day]').evaluateAll(nodes=>nodes.map(node=>node.dataset.bugDay)),['2026-10-20','2026-10-19','unknown']);
  assert.equal(await page.locator('[data-bug-resolve]').count(),0);
  await page.locator('[data-bug="'+'3'.repeat(32)+'"]').click();
  await page.locator('[data-bug-history="'+'3'.repeat(32)+'"] > summary').click();
  await Promise.resolve();
  await page.locator('[data-bug-day="unknown"] > summary').click();
  await page.locator('[data-bug="'+'5'.repeat(32)+'"]').click();
  await page.locator('[data-bug-history="'+'5'.repeat(32)+'"] > summary').click();
  assert.match(await page.locator('[data-bug-history="'+'5'.repeat(32)+'"]').innerText(),/7 earlier occurrences without recorded dates/);
  await page.locator('[data-bug-tab="open"]').click();
  assert.notEqual(await history.getAttribute('open'),null,'History expansion survives tab changes');
  await page.setViewportSize({width:390,height:844});
  await Promise.resolve();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile page has no horizontal overflow');
  await page.locator('[data-bug-resolve="'+'1'.repeat(32)+'"]').click();
  await page.locator('[data-bug="'+'1'.repeat(32)+'"]').waitFor({state:'detached'});
  await page.locator('[data-bug-tab="done"]').click();
  assert.equal(await page.locator('[data-bug="'+'1'.repeat(32)+'"]').count(),1);
  const resolvedCard=page.locator('[data-bug="'+'1'.repeat(32)+'"]'),resolvedDay=resolvedCard.locator('xpath=ancestor::details[contains(@class,"bug-day")]');
  if(await resolvedDay.getAttribute('open')===null)await resolvedDay.locator(':scope > summary').click();
  await resolvedCard.waitFor({state:'visible'});
  await resolvedCard.scrollIntoViewIfNeeded();
  assert.match(await resolvedCard.innerText(),/Resolved:/);
  assert.deepEqual(errors,[]);
  console.log('Bugs UI passed: date order, Active/Resolved grouping, collapsible history, legacy unknown dates, tab state, local resolve, desktop/mobile.');
}finally{await browser?.close();server.kill();await once(server,'exit');}
